create table if not exists public.equipment_submissions (
    id bigint generated by default as identity primary key,
    name text not null check (char_length(btrim(name)) between 1 and 100),
    category text not null check (char_length(btrim(category)) between 1 and 100),
    purpose text not null check (char_length(btrim(purpose)) between 1 and 1500),
    structure text not null check (char_length(btrim(structure)) between 1 and 1500),
    usage text not null check (char_length(btrim(usage)) between 1 and 2500),
    caution text not null check (char_length(btrim(caution)) between 1 and 1500),
    image_url text check (
        image_url is null
        or (char_length(image_url) <= 1000 and image_url ~ '^https://')
    ),
    status text not null default 'pending'
        check (status in ('pending', 'approved', 'rejected')),
    reviewer_note text check (
        reviewer_note is null or char_length(reviewer_note) <= 1000
    ),
    created_at timestamptz not null default now(),
    reviewed_at timestamptz
);

alter table public.equipment_submissions enable row level security;

revoke all on table public.equipment_submissions from anon, authenticated;
grant insert (
    name,
    category,
    purpose,
    structure,
    usage,
    caution,
    image_url
) on table public.equipment_submissions to anon, authenticated;
grant select, insert, update, delete
    on table public.equipment_submissions to service_role;

revoke all on sequence public.equipment_submissions_id_seq
    from anon, authenticated;
grant usage, select on sequence public.equipment_submissions_id_seq
    to anon, authenticated, service_role;

drop policy if exists equipment_submissions_insert_public
    on public.equipment_submissions;
create policy equipment_submissions_insert_public
    on public.equipment_submissions
    for insert
    to anon, authenticated
    with check (
        status = 'pending'
        and reviewed_at is null
        and reviewer_note is null
    );

create unique index if not exists equipment_submissions_pending_name_unique
    on public.equipment_submissions (lower(btrim(name)))
    where status = 'pending';

create unique index if not exists equipment_name_normalized_unique
    on public.equipment (lower(btrim(name)));

grant delete on table public.analysis_history to anon, authenticated;

drop policy if exists analysis_history_delete_public
    on public.analysis_history;
create policy analysis_history_delete_public
    on public.analysis_history
    for delete
    to anon, authenticated
    using (true);

create or replace function public.review_equipment_submission(
    p_id bigint,
    p_action text,
    p_reviewer_note text default null,
    p_image_url text default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $function$
declare
    submission public.equipment_submissions%rowtype;
    equipment_row public.equipment%rowtype;
    final_image_url text;
begin
    if p_action not in ('approve', 'reject') then
        raise exception using
            errcode = '22023',
            message = '승인 또는 반려 동작만 사용할 수 있습니다.';
    end if;

    if p_reviewer_note is not null and char_length(p_reviewer_note) > 1000 then
        raise exception using
            errcode = '22001',
            message = '검토 메모는 1000자 이하여야 합니다.';
    end if;

    select * into submission
      from public.equipment_submissions
     where id = p_id
     for update;

    if not found then
        raise exception using
            errcode = 'P0002',
            message = '검토할 제안을 찾지 못했습니다.';
    end if;

    if submission.status <> 'pending' then
        raise exception using
            errcode = '23505',
            message = '이미 검토가 끝난 제안입니다.';
    end if;

    if p_action = 'reject' then
        update public.equipment_submissions
           set status = 'rejected',
               reviewer_note = nullif(btrim(p_reviewer_note), ''),
               reviewed_at = now()
         where id = submission.id;

        return jsonb_build_object('id', submission.id, 'status', 'rejected');
    end if;

    final_image_url := coalesce(nullif(btrim(p_image_url), ''), submission.image_url);

    if final_image_url is null or final_image_url !~ '^https://' then
        raise exception using
            errcode = '22023',
            message = '승인하려면 https:// 사진 주소가 필요합니다.';
    end if;

    insert into public.equipment (
        name,
        category,
        purpose,
        structure,
        usage,
        caution,
        image_url
    )
    values (
        btrim(submission.name),
        btrim(submission.category),
        btrim(submission.purpose),
        btrim(submission.structure),
        btrim(submission.usage),
        btrim(submission.caution),
        final_image_url
    )
    returning * into equipment_row;

    update public.equipment_submissions
       set status = 'approved',
           image_url = final_image_url,
           reviewer_note = nullif(btrim(p_reviewer_note), ''),
           reviewed_at = now()
     where id = submission.id;

    return jsonb_build_object(
        'id', submission.id,
        'status', 'approved',
        'equipment_id', equipment_row.id,
        'equipment_name', equipment_row.name
    );

exception
    when unique_violation then
        raise exception using
            errcode = '23505',
            message = '같은 이름의 기구가 이미 사전에 등록되어 있습니다.';
end;
$function$;

revoke all on function public.review_equipment_submission(bigint, text, text, text)
    from public, anon, authenticated;
grant execute on function public.review_equipment_submission(bigint, text, text, text)
    to service_role;

notify pgrst, 'reload schema';
